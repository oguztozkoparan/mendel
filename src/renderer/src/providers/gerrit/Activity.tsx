import { useState } from 'react'
import { Button } from 'react-aria-components'
import type { GerritChange, GerritComment } from '../../../../shared/gerrit'
import { Segmented, Switch } from '../../controls'
import s from './Gerrit.module.css'
import { fileLabel, isAutogenerated, relTime, shortDate, splitMessage, threadsOf, who } from './util'

type Message = NonNullable<GerritChange['messages']>[number]
const COLLAPSED = 5

/** Gerrit's Change Log | Comment Threads (PLAN.md §3.8): messages oldest first like Gerrit, all published threads of the change. */
export function Activity({ messages, comments, onOpenThread }: { messages: Message[]; comments: GerritComment[]; onOpenThread(thread: GerritComment[]): void }) {
  const threads = threadsOf(comments)
  const anyUnresolved = threads.some((t) => t.at(-1)!.unresolved)
  const [tab, setTab] = useState<'log' | 'threads'>('log')
  const [onlyComments, setOnlyComments] = useState(false)
  const [unresolvedOnly, setUnresolvedOnly] = useState<boolean | null>(null)
  const [showAll, setShowAll] = useState(false)
  const unresolvedFilter = (unresolvedOnly ?? anyUnresolved) && anyUnresolved

  const log = messages.filter((m) => !onlyComments || (!isAutogenerated(m) && splitMessage(m.message).userText))
  const list = threads.filter((t) => !unresolvedFilter || t.at(-1)!.unresolved)
  const count = tab === 'log' ? log.length : list.length
  // Newest at the bottom, so collapsing keeps the last rows.
  const hidden = showAll ? 0 : Math.max(0, count - COLLAPSED)

  return (
    <section aria-label="Activity" className={s.block}>
      <div className={s.activityBar}>
        <Segmented<'log' | 'threads'>
          label="Activity view"
          value={tab}
          options={[
            ['log', 'Change Log'],
            ['threads', `Comment Threads${threads.length ? ` (${threads.length})` : ''}`]
          ]}
          onChange={setTab}
        />
        <span className={s.grow} />
        {tab === 'log' ? (
          <Switch key="log" isSelected={onlyComments} onChange={setOnlyComments}>
            Only comments
          </Switch>
        ) : (
          <Switch key="threads" isSelected={unresolvedFilter} onChange={setUnresolvedOnly} isDisabled={!anyUnresolved}>
            Unresolved only
          </Switch>
        )}
      </div>
      {!!hidden && (
        <Button className={s.link} onPress={() => setShowAll(true)}>
          {`Show all ${count}`}
        </Button>
      )}
      {!count && <p className={s.meta}>{tab === 'log' ? 'No messages' : 'No comment threads'}</p>}
      <ul className={s.activity} aria-label={tab === 'log' ? 'Change Log' : 'Comment Threads'}>
        {tab === 'log' ? log.slice(hidden).map((m) => <LogRow key={m.id} m={m} />) : list.slice(hidden).map((t) => <ThreadRow key={t[0].id} t={t} onOpen={() => onOpenThread(t)} />)}
      </ul>
    </section>
  )
}

const voteSign = (v: string) => (/\+\d+$/.test(v) ? 1 : /[^-]-\d+$/.test(v) ? -1 : 0)

function LogRow({ m }: { m: Message }) {
  const [open, setOpen] = useState(false)
  const { prefix, votes, body } = splitMessage(m.message)
  const long = body.length > 300 || body.split('\n').length > 4
  const onBehalf = m.real_author && m.real_author._account_id !== m.author?._account_id ? ` (by ${who(m.real_author)})` : ''
  return (
    <li className={s.logRow} data-system={isAutogenerated(m) || undefined}>
      <div className={s.commentHead}>
        <strong>{who(m.author) + onBehalf}</strong>
        {prefix && <span className={s.meta}>{prefix}</span>}
        {votes.map((v) => (
          <span key={v} className={s.vote} data-vote={voteSign(v)}>
            {v}
          </span>
        ))}
        <span className={s.grow} />
        {m._revision_number && <span className={s.psChip}>PS {m._revision_number}</span>}
        <span className={s.meta} title={shortDate(m.date)}>
          {relTime(m.date)}
        </span>
      </div>
      {body && (
        <p className={s.plain} data-clamp={(long && !open) || undefined}>
          {body}
        </p>
      )}
      {long && (
        <Button className={s.link} onPress={() => setOpen(!open)}>
          {open ? 'Show less' : 'Show more'}
        </Button>
      )}
    </li>
  )
}

function ThreadRow({ t, onOpen }: { t: GerritComment[]; onOpen(): void }) {
  const root = t[0]
  const unresolved = !!t.at(-1)!.unresolved
  const replies = t.length - 1
  const where = root.line ? `Line ${root.line}` : 'File comment'
  return (
    <li className={s.logRow}>
      <Button className={s.threadRow} aria-label={`${fileLabel(root.path)} ${where} by ${who(root.author)}`} onPress={onOpen}>
        <span className={s.commentHead}>
          <strong className={s.grow}>{fileLabel(root.path)}</strong>
          <span className={s.meta}>{where}</span>
          {root.patch_set && <span className={s.psChip}>PS {root.patch_set}</span>}
          <span className={s.state} data-unresolved={unresolved || undefined}>
            {unresolved ? 'Unresolved' : 'Resolved'}
          </span>
        </span>
        <span className={s.excerpt}>
          <strong>{who(root.author)}</strong> {root.message ?? ''}
        </span>
        <span className={s.meta}>{replies ? `${replies} ${replies === 1 ? 'reply' : 'replies'}` : 'No replies'}</span>
      </Button>
    </li>
  )
}
